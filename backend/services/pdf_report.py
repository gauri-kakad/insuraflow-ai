import io
from datetime import datetime, timezone
from typing import Dict, Any, Optional
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.units import mm


def generate_claim_assessment_pdf(
    claim: Dict[str, Any],
    assessment_doc: Optional[Dict[str, Any]],
    audit_logs: list[Dict[str, Any]],
) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
    )

    styles = getSampleStyleSheet()
    navy = colors.HexColor("#0F2942")
    slate = colors.HexColor("#475569")
    light_bg = colors.HexColor("#F8FAFC")
    border_grey = colors.HexColor("#CBD5E1")

    title_style = ParagraphStyle(
        "TitleStyle",
        parent=styles["Heading1"],
        fontSize=18,
        textColor=navy,
        spaceAfter=4,
    )
    subtitle_style = ParagraphStyle(
        "SubTitle",
        parent=styles["Normal"],
        fontSize=9,
        textColor=slate,
        spaceAfter=12,
    )
    section_style = ParagraphStyle(
        "SectionHeader",
        parent=styles["Heading2"],
        fontSize=12,
        textColor=navy,
        spaceBefore=12,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "BodyText",
        parent=styles["Normal"],
        fontSize=9.5,
        leading=14,
        textColor=colors.HexColor("#1E293B"),
    )

    story = []

    # Header
    story.append(Paragraph("INSURAFLOW AI — MOTOR CLAIM ASSESSMENT REPORT", title_style))
    gen_ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    story.append(
        Paragraph(
            f"Decision-Support Audit Dossier | Claim ID: <b>{claim.get('claim_id')}</b> | Generated: {gen_ts}",
            subtitle_style,
        )
    )
    story.append(HRFlowable(width="100%", thickness=1, color=navy))
    story.append(Spacer(1, 8))

    # Governance Disclaimer Banner
    disclaimer_table = Table(
        [[
            Paragraph(
                "<b>GOVERNANCE NOTICE:</b> This report is generated by InsuraFlow AI as a decision-support aid. "
                "AI agents do not approve or reject insurance claims. Final settlement authority rests exclusively with an authorized human claims officer.",
                body_style,
            )
        ]],
        colWidths=[174 * mm],
    )
    disclaimer_table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EFF6FF")),
            ("BOX", (0, 0), (-1, -1), 0.75, colors.HexColor("#3B82F6")),
            ("PADDING", (0, 0), (-1, -1), 8),
        ])
    )
    story.append(disclaimer_table)
    story.append(Spacer(1, 10))

    # 1. Claim & Policyholder Overview
    story.append(Paragraph("1. Claim & Vehicle Overview", section_style))
    overview_data = [
        ["Claim Reference", claim.get("claim_id", "N/A"), "Current Status", claim.get("status", "N/A")],
        ["Policyholder", claim.get("policyholder_name", "N/A"), "Policy Number", claim.get("policy_number", "N/A")],
        ["Vehicle Reg.", claim.get("vehicle_number", "N/A"), "Vehicle Model", claim.get("vehicle_model", "N/A")],
        ["Accident Date", claim.get("accident_date", "N/A"), "Location", claim.get("accident_location", "N/A")],
        [
            "Claimed Amount",
            f"INR {float(claim.get('claimed_amount', 0)):,.2f}",
            "Risk Classification",
            f"{claim.get('risk_level', 'Pending')} ({claim.get('risk_score', 'N/A')}/100)",
        ],
    ]
    t1 = Table(overview_data, colWidths=[36 * mm, 51 * mm, 36 * mm, 51 * mm])
    t1.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (0, -1), light_bg),
            ("BACKGROUND", (2, 0), (2, -1), light_bg),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("FONTNAME", (2, 0), (2, -1), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("GRID", (0, 0), (-1, -1), 0.5, border_grey),
            ("PADDING", (0, 0), (-1, -1), 6),
        ])
    )
    story.append(t1)
    story.append(Spacer(1, 6))
    story.append(Paragraph(f"<b>Reported Damage:</b> {claim.get('damage_description', 'N/A')}", body_style))

    if assessment_doc:
        final_a = assessment_doc.get("final_assessment", {})
        pol_v = assessment_doc.get("policy_verification", {})
        fraud_a = assessment_doc.get("fraud_analysis", {})

        # 2. AI Assessment Summary
        story.append(Paragraph("2. Multi-Agent Assessment Synthesis", section_style))
        story.append(Paragraph(f"<b>Engine Mode:</b> {assessment_doc.get('model_used', 'N/A')}", body_style))
        story.append(Paragraph(f"<b>Recommended Next Action:</b> {final_a.get('recommended_next_action', 'N/A')}", body_style))
        elig = final_a.get("estimated_eligible_amount")
        elig_str = f"INR {float(elig):,.2f} (subject to officer verification)" if elig is not None else "Withheld pending verification"
        story.append(Paragraph(f"<b>Preliminary Eligible Estimate:</b> {elig_str}", body_style))
        story.append(Spacer(1, 4))
        story.append(Paragraph(final_a.get("explanation", ""), body_style))

        # 3. Policy Verification
        story.append(Paragraph("3. Policy Verification Findings", section_style))
        story.append(Paragraph(f"<b>Coverage Status:</b> {final_a.get('policy_verification_status', 'N/A')}", body_style))
        story.append(Paragraph(pol_v.get("explanation", ""), body_style))
        if pol_v.get("missing_documents"):
            story.append(
                Paragraph(
                    f"<b>Missing Supporting Documents:</b> {', '.join(pol_v['missing_documents'])}",
                    body_style,
                )
            )

        # 4. Fraud & Anomaly Indicators
        story.append(Paragraph("4. Fraud & Anomaly Risk Breakdown", section_style))
        story.append(
            Paragraph(
                f"<b>Risk Score:</b> {fraud_a.get('risk_score', 0)}/100 ({fraud_a.get('risk_level', 'Low')} Risk)",
                body_style,
            )
        )
        story.append(Paragraph(fraud_a.get("explanation", ""), body_style))
        indicators = fraud_a.get("indicators", [])
        if indicators:
            story.append(Spacer(1, 4))
            ind_rows = [["Indicator Type", "Severity", "Source", "Evidence"]]
            for ind in indicators:
                ind_rows.append([
                    ind.get("type", ""),
                    ind.get("severity", ""),
                    ind.get("source", ""),
                    Paragraph(ind.get("evidence", ""), body_style),
                ])
            t_ind = Table(ind_rows, colWidths=[38 * mm, 20 * mm, 32 * mm, 84 * mm])
            t_ind.setStyle(
                TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), navy),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ("GRID", (0, 0), (-1, -1), 0.5, border_grey),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("PADDING", (0, 0), (-1, -1), 5),
                ])
            )
            story.append(t_ind)

    # 5. Human Review & Audit History
    story.append(Paragraph("5. Human Review & Audit Log", section_style))
    if claim.get("human_review"):
        hr = claim["human_review"]
        story.append(
            Paragraph(
                f"<b>Latest Officer Decision:</b> {hr.get('decision')} by {hr.get('reviewer_name')} at {hr.get('reviewed_at')}",
                body_style,
            )
        )
        story.append(Paragraph(f"<b>Officer Notes:</b> {hr.get('notes')}", body_style))
        story.append(Spacer(1, 4))

    if audit_logs:
        aud_rows = [["Timestamp (UTC)", "Actor", "Action", "Details"]]
        for log in audit_logs[:10]:
            aud_rows.append([
                log.get("timestamp", "")[:19].replace("T", " "),
                log.get("actor", ""),
                log.get("action", ""),
                Paragraph(log.get("details", ""), body_style),
            ])
        t_aud = Table(aud_rows, colWidths=[34 * mm, 38 * mm, 38 * mm, 64 * mm])
        t_aud.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), light_bg),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 7.5),
                ("GRID", (0, 0), (-1, -1), 0.5, border_grey),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("PADDING", (0, 0), (-1, -1), 4),
            ])
        )
        story.append(t_aud)

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
